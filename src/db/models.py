"""SQLAlchemy declarative models and Alembic's metadata target (Phase 1).

Phase 1 intentionally defines exactly ONE table — ``app_meta`` — so the
foundation can be verified end to end (connect → migrate up → read/write →
migrate down) without pre-empting Phase 2 (``users``) or Phase 5
(``conversations`` / ``messages``).

Importing this module loads SQLAlchemy only. It performs no I/O and opens no
connection.

Alembic's ``target_metadata`` points at :data:`Base.metadata`. The naming
convention below is declared here (not in ``alembic/env.py``) so that
autogenerated migrations produce stable, explicit constraint names — without it
Alembic emits anonymous constraints that it cannot later diff or drop reliably.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import DateTime, MetaData, String, Text, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

__all__ = ["AppMeta", "Base", "NAMING_CONVENTION"]

#: Stable constraint names so ``alembic revision --autogenerate`` can diff and
#: drop constraints deterministically in later phases.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base for every AuditPro table."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class AppMeta(Base):
    """Tiny key/value table — the Phase 1 connectivity probe.

    It carries no user data. Its only jobs are:
      * prove a real PostgreSQL round trip (insert / select / update / delete);
      * give ``alembic upgrade head`` something concrete to create and
        ``alembic downgrade base`` something concrete to drop.

    A later phase may use it for deployment metadata (e.g. schema-compat flags).
    Do not grow it into a settings store — application configuration stays in
    the environment.
    """

    __tablename__ = "app_meta"

    key: Mapped[str] = mapped_column(String(255), primary_key=True)
    value: Mapped[str] = mapped_column(Text, nullable=False)
    # server_default covers INSERT; onupdate covers UPDATE. Without onupdate a
    # row named `updated_at` would keep its insert timestamp forever.
    # `onupdate` is applied client-side by SQLAlchemy and is NOT part of the
    # DDL, so adding it requires no migration.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )
